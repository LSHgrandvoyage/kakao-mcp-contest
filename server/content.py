def select_clauses(situation: str) -> list[dict]:
    """상황 서술에서 키워드를 찾아 관련 특약 + baseline 을 반환."""
    s = situation or ""
    chosen = list(_BASELINE)
    for c in _CONDITIONAL:
        if any(kw in s for kw in c["triggers"]):
            chosen.append({"text": c["text"], "why": c["why"]})
    return chosen
